-- Prosjektchat v1 (2. nov. 2026). Migrasjon `prosjekt_meldingar`. Køyrd i Supabase.
create table public.prosjekt_meldingar (
  id          bigint generated by default as identity primary key,
  project_id  bigint not null references public.projects(id) on delete cascade,
  user_id     uuid not null references auth.users(id),
  tekst       text not null check (length(btrim(tekst)) > 0 and length(tekst) <= 4000),
  svar_til    bigint references public.prosjekt_meldingar(id) on delete set null,
  tema        text,
  system      boolean not null default false,
  created_at  timestamptz not null default now()
);
create index prosjekt_meldingar_prosjekt_idx on public.prosjekt_meldingar (project_id, created_at);
alter table public.prosjekt_meldingar enable row level security;
-- Same tilgang som prosjektet. Ingen update/delete-policy (ingen redigering/sletting i v1).
create policy prosjekt_meldingar_select on public.prosjekt_meldingar for select to authenticated using (public.kan_se_prosjekt(project_id));
create policy prosjekt_meldingar_insert on public.prosjekt_meldingar for insert to authenticated
  with check (public.kan_se_prosjekt(project_id) and user_id = auth.uid() and system = false);
alter publication supabase_realtime add table public.prosjekt_meldingar;
