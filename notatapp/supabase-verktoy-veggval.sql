-- 13. nov. 2026. Migrasjon `verktoy_veggval`: veggval frå Verktøy → Veggvelgar, lagra per prosjekt.
-- Køyrast manuelt i Supabase SQL Editor. Alle med tilgang til prosjektet ser og kan lagre veggval; berre forfattaren eller prosjektadministrator kan slette.
create table public.verktoy_veggval (
  id               bigint generated by default as identity primary key,
  project_id       bigint not null references public.projects(id) on delete cascade,
  veggkode         text not null,
  familie          text not null default '',
  romnamn          text not null default '',
  merknad          text not null default '',
  krav             jsonb not null default '{}'::jsonb,
  resultat         jsonb not null default '{}'::jsonb,
  datakjelde_dato  text not null default '',
  created_by       uuid not null default auth.uid() references auth.users(id),
  created_at       timestamptz not null default now()
);
create index verktoy_veggval_prosjekt_idx on public.verktoy_veggval (project_id, created_at desc);
alter table public.verktoy_veggval enable row level security;
create policy verktoy_veggval_select on public.verktoy_veggval for select to authenticated using (public.kan_se_prosjekt(project_id));
create policy verktoy_veggval_insert on public.verktoy_veggval for insert to authenticated with check (public.kan_se_prosjekt(project_id) and created_by = auth.uid());
create policy verktoy_veggval_delete on public.verktoy_veggval for delete to authenticated
  using (public.kan_se_prosjekt(project_id) and (created_by = auth.uid() or public.kan_administrere_prosjekt(project_id)));
-- Rollback: drop table public.verktoy_veggval;
