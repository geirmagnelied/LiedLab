-- 10. nov. 2026. Migrasjon `framdrift_statusar`: lagra statusar (frosne bilete av prosjektplanen) og siste kladd, frå Prosjektplan → «Lagre status».
-- Køyrast manuelt i Supabase SQL Editor. Alle med tilgang til prosjektet ser og kan lagre statusar; berre forfattaren eller prosjektadministrator kan slette ein status.
-- Kladden (type = 'kladd') er ein automatisk kopi av planen før ein status vert henta fram; berre éin kladd per prosjekt vert teken vare på, og kven som helst med
-- prosjekttilgang kan erstatte han.
create table public.framdrift_statusar (
  id           bigint generated by default as identity primary key,
  project_id   bigint not null references public.projects(id) on delete cascade,
  type         text not null default 'status' check (type in ('status','kladd')),
  namn         text not null,
  beskriving   text not null default '',
  periode_type text check (periode_type in ('manad','veke')),
  periode_fra  date,
  periode_til  date,
  elementer    jsonb not null default '[]'::jsonb,
  palop        jsonb not null default '{}'::jsonb,
  created_by   uuid not null default auth.uid() references auth.users(id),
  created_at   timestamptz not null default now()
);
create index framdrift_statusar_prosjekt_idx on public.framdrift_statusar (project_id, created_at desc);
alter table public.framdrift_statusar enable row level security;
create policy framdrift_statusar_select on public.framdrift_statusar for select to authenticated using (public.kan_se_prosjekt(project_id));
create policy framdrift_statusar_insert on public.framdrift_statusar for insert to authenticated with check (public.kan_se_prosjekt(project_id) and created_by = auth.uid());
create policy framdrift_statusar_delete on public.framdrift_statusar for delete to authenticated
  using (public.kan_se_prosjekt(project_id) and (created_by = auth.uid() or public.kan_administrere_prosjekt(project_id) or type = 'kladd'));
-- Rollback: drop table public.framdrift_statusar;
