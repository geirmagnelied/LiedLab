-- Kanban-modul (Gjeremål → Oppgåver), 24. okt. 2026. Sjå claude/kanban-modul.md. Køyrt via Supabase MCP.
CREATE TABLE IF NOT EXISTS kanban_kort (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID   NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  project_id  BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  tittel      TEXT   NOT NULL,
  skildring   TEXT   DEFAULT '',
  status      TEXT   NOT NULL DEFAULT 'ide'
              CHECK (status IN ('ide','komande','under_arbeid','godkjenning_intern','godkjenning_ekstern','ferdig')),
  ansvarleg   TEXT   DEFAULT '',
  fase        TEXT,
  frist       DATE,
  farge       TEXT,
  sak_id      BIGINT REFERENCES cases(id) ON DELETE SET NULL,
  oppgave_ref JSONB,                       -- { note_id, task_id }
  framdrift_aktivitet_ref JSONB,           -- { element_id }
  sortering   INT    DEFAULT 0,
  ferdig_dato TIMESTAMPTZ,
  created_at  TIMESTAMPTZ DEFAULT NOW(),
  updated_at  TIMESTAMPTZ DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_kanban_kort_project ON kanban_kort(project_id);
ALTER TABLE kanban_kort ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "kanban_kort_select" ON kanban_kort;
DROP POLICY IF EXISTS "kanban_kort_insert" ON kanban_kort;
DROP POLICY IF EXISTS "kanban_kort_update" ON kanban_kort;
DROP POLICY IF EXISTS "kanban_kort_delete" ON kanban_kort;
CREATE POLICY "kanban_kort_select" ON kanban_kort FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "kanban_kort_insert" ON kanban_kort FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "kanban_kort_update" ON kanban_kort FOR UPDATE USING (auth.uid() = user_id);
CREATE POLICY "kanban_kort_delete" ON kanban_kort FOR DELETE USING (auth.uid() = user_id);

-- 24. okt. 2026 (2): tavle per fase + lenkje til DTM-leveranse. Køyrt via Supabase MCP.
CREATE TABLE IF NOT EXISTS kanban_tavler (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID   NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  project_id  BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  fase        TEXT   NOT NULL CHECK (fase IN ('skisse','forprosjekt','soknad','detalj')),
  avslutta    BOOLEAN NOT NULL DEFAULT false,
  created_at  TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (user_id, project_id, fase)
);
ALTER TABLE kanban_tavler ENABLE ROW LEVEL SECURITY;
CREATE POLICY "kanban_tavler_select" ON kanban_tavler FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "kanban_tavler_insert" ON kanban_tavler FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "kanban_tavler_update" ON kanban_tavler FOR UPDATE USING (auth.uid() = user_id);
CREATE POLICY "kanban_tavler_delete" ON kanban_tavler FOR DELETE USING (auth.uid() = user_id);
ALTER TABLE kanban_kort ADD COLUMN IF NOT EXISTS tavle_id BIGINT REFERENCES kanban_tavler(id) ON DELETE CASCADE;
ALTER TABLE kanban_kort ADD COLUMN IF NOT EXISTS dtm_ref JSONB;   -- { dokument_id, sist_status, skjult }
CREATE INDEX IF NOT EXISTS idx_kanban_kort_tavle ON kanban_kort(tavle_id);
