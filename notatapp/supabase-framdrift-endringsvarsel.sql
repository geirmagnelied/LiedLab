-- 8. nov. 2026. Migrasjon `framdrift_endringsvarsel`: endringsvarsel (utkast/ferdig) frå Prosjektplan → «＋ Ny» → «Ny endring».
-- Køyrast manuelt i Supabase SQL Editor. Same tilgang som framdrift_rapportar: synleg for alle med tilgang til prosjektet,
-- endring/sletting av forfattaren eller prosjektadministrator. Vedlegg ligg i lagringsbøtta `dtm-resultatdokument`
-- under <user_id>/<project_id>/endringsvarsel/<mappe>/<filnamn> (eksisterande policyar prosjektfiler_* dekkjer dette).
create table public.framdrift_endringsvarsel (
  id          bigint generated by default as identity primary key,
  project_id  bigint not null references public.projects(id) on delete cascade,
  tittel      text not null default '',
  status      text not null default 'utkast' check (status in ('utkast','ferdig')),
  innhald     jsonb not null default '{}'::jsonb,
  created_by  uuid not null default auth.uid() references auth.users(id),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index framdrift_endringsvarsel_prosjekt_idx on public.framdrift_endringsvarsel (project_id, created_at);
alter table public.framdrift_endringsvarsel enable row level security;
create policy framdrift_endringsvarsel_select on public.framdrift_endringsvarsel for select to authenticated using (public.kan_se_prosjekt(project_id));
create policy framdrift_endringsvarsel_insert on public.framdrift_endringsvarsel for insert to authenticated with check (public.kan_se_prosjekt(project_id) and created_by = auth.uid());
create policy framdrift_endringsvarsel_update on public.framdrift_endringsvarsel for update to authenticated
  using (public.kan_se_prosjekt(project_id) and (created_by = auth.uid() or public.kan_administrere_prosjekt(project_id)))
  with check (public.kan_se_prosjekt(project_id) and (created_by = auth.uid() or public.kan_administrere_prosjekt(project_id)));
create policy framdrift_endringsvarsel_delete on public.framdrift_endringsvarsel for delete to authenticated
  using (public.kan_se_prosjekt(project_id) and (created_by = auth.uid() or public.kan_administrere_prosjekt(project_id)));
-- Rollback: drop table public.framdrift_endringsvarsel;
