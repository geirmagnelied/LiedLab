-- Kontorchat (2. nov. 2026): generell chat for heile kontoret, vist i Dashboard når «alle prosjekt» er valt. Migrasjon `kontor_meldingar`, køyrd i Supabase.
create table public.kontor_meldingar (
  id          bigint generated by default as identity primary key,
  office_id   bigint not null references public.offices(id) on delete cascade,
  user_id     uuid not null references auth.users(id),
  tekst       text not null check (length(btrim(tekst)) > 0 and length(tekst) <= 4000),
  created_at  timestamptz not null default now()
);
create index kontor_meldingar_kontor_idx on public.kontor_meldingar (office_id, created_at);
alter table public.kontor_meldingar enable row level security;
create policy kontor_meldingar_select on public.kontor_meldingar for select to authenticated using (public.is_office_member(office_id));
create policy kontor_meldingar_insert on public.kontor_meldingar for insert to authenticated
  with check (public.is_office_member(office_id) and user_id = auth.uid());
alter publication supabase_realtime add table public.kontor_meldingar;
